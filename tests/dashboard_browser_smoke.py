"""Browser integration test. Start dashboard first; AI responses are stubbed."""
from pathlib import Path
import os
from playwright.sync_api import sync_playwright, expect

with sync_playwright() as p:
    browser = p.chromium.launch(channel=os.getenv("BROWSER_CHANNEL", "msedge") or None, headless=True)
    page = browser.new_page(viewport={"width":1560,"height":1080})
    errors = []
    page.on("pageerror", lambda error: errors.append(str(error)))
    base = os.getenv("DASHBOARD_URL", "http://127.0.0.1:8000")
    page.goto(base)
    expect(page.locator("#status")).to_contain_text("입력 대기")
    content = page.locator("#draft-editor .tiptap")
    content.click()
    page.locator("#block-type").select_option("1")
    page.keyboard.insert_text("대학생을 위한 AI 학습 플래너")
    expect(content.locator("h1")).to_have_text("대학생을 위한 AI 학습 플래너")
    page.keyboard.press("Enter")
    page.keyboard.insert_text("학습 일정을 관리하고 꾸준한 실천을 돕습니다.")
    page.keyboard.press("Home")
    page.keyboard.press("Shift+End")
    page.locator('#editor-toolbar [data-editor-action="bold"]').click()
    expect(content.locator("strong")).to_have_text("학습 일정을 관리하고 꾸준한 실천을 돕습니다.")
    page.keyboard.press("ArrowRight")
    page.keyboard.press("Enter")
    page.keyboard.insert_text("/")
    expect(page.locator("#slash-menu")).to_be_visible()
    page.locator("#slash-menu button").filter(has_text="체크리스트").click()
    page.keyboard.insert_text("사용자 인터뷰 진행")
    content.locator('input[type="checkbox"]').click()
    expect(content.locator('input[type="checkbox"]')).to_be_checked()
    content.locator('li[data-checked] p').click()
    page.keyboard.press("End")
    page.keyboard.press("Enter")
    page.keyboard.press("Enter")
    page.locator('#editor-toolbar [data-editor-action="table"]').click()
    expect(content.locator("table")).to_have_count(1)
    content.locator("th").first.click()
    page.keyboard.insert_text("기능")
    page.locator('[data-editor-action="addRow"]').click()
    expect(content.locator("tr")).to_have_count(4)
    page.locator("#save-draft").click()
    expect(page.locator("#draft-status")).to_have_text("모든 변경사항 저장됨")
    first_session = page.evaluate("localStorage.getItem('div-session')")
    page.reload()
    expect(page.locator("#status")).to_contain_text("입력 대기")
    expect(content.locator("h1")).to_have_text("대학생을 위한 AI 학습 플래너")
    expect(content.locator("tr")).to_have_count(4)
    expect(content.locator('input[type="checkbox"]')).to_be_checked()
    expect(page.locator("#outline")).to_contain_text("대학생을 위한 AI 학습 플래너")
    page.locator("#preview-tab").click()
    expect(page.locator("#document table")).to_have_count(1)
    page.locator("#edit-tab").click()
    content.locator("h1").click()
    page.keyboard.press("Home")
    page.keyboard.press("Shift+End")
    page.locator("#ask-selection").click()
    expect(page.locator("#selection-panel")).to_be_visible()
    requests = []
    def revision(route):
        requests.append(route.request.post_data_json)
        route.fulfill(json={"text":"학습 계획의 실천을 돕습니다.", "html":"<p>학습 계획의 실천을 돕습니다.</p>"})
    page.route("**/api/sessions/*/revise", revision)
    page.locator("#request-revision").click()
    expect(page.locator("#revision-result")).to_be_visible()
    expect(content).to_contain_text("대학생을 위한 AI 학습 플래너")
    page.locator("#apply-revision").click()
    expect(content).to_contain_text("학습 계획의 실천을 돕습니다.")
    page.locator('#editor-toolbar [data-editor-action="undo"]').click()
    expect(content).to_contain_text("대학생을 위한 AI 학습 플래너")
    assert requests[0]["selection"] == "대학생을 위한 AI 학습 플래너"
    content.locator("h1").click()
    page.keyboard.press("Home")
    page.keyboard.press("Shift+End")
    page.locator("#ask-selection").click()
    page.locator("#request-revision").click()
    expect(page.locator("#revision-result")).to_be_visible()
    content.locator("h1").click()
    page.keyboard.press("End")
    page.keyboard.insert_text(" v2")
    page.locator("#apply-revision").click()
    expect(page.locator("#revision-status")).to_contain_text("문서가 바뀌었습니다")
    expect(content).to_contain_text("대학생을 위한 AI 학습 플래너")
    with page.expect_download() as download:
        page.locator("#download-draft").click()
    exported = Path(download.value.path()).read_text(encoding="utf-8")
    assert "# 대학생" in exported and "[x]" in exported and "기능" in exported
    page.locator("#close-selection").click()
    page.locator("#save-draft").click()
    expect(page.locator("#draft-status")).to_have_text("모든 변경사항 저장됨")
    Path("output").mkdir(exist_ok=True)
    page.screenshot(path="output/document-editor-preview.png", full_page=True)
    page.set_viewport_size({"width":390,"height":844})
    assert not page.evaluate("document.documentElement.scrollWidth > innerWidth")
    page.set_viewport_size({"width":1560,"height":1080})
    page.locator("#new").click()
    page.wait_for_function("old => localStorage.getItem('div-session') !== old", arg=first_session)
    assert page.request.get(f"{base}/api/sessions/{first_session}").json()["draft"]
    expect(content).to_have_text("")
    expect(page.locator('#editor-toolbar [data-editor-action="undo"]')).to_be_disabled()
    current = page.evaluate("localStorage.getItem('div-session')")
    assert page.request.put(f"{base}/api/sessions/{current}/draft", data={"markdown":"다른 탭의 최신본", "base_revision":0}).status == 200
    content.click()
    page.keyboard.insert_text("내 편집 사본")
    expect(page.locator('#draft-conflict')).to_be_visible(timeout=10000)
    assert page.request.get(f"{base}/api/sessions/{current}").json()['draft'] == '다른 탭의 최신본'
    page.locator('#copy-draft').click()
    page.wait_for_function("old => localStorage.getItem('div-session') !== old", arg=current)
    expect(content).to_contain_text('내 편집 사본')
    page.locator('#refresh-documents').click()
    expect(page.locator('#document-list')).to_contain_text('다른 탭의 최신본')
    page.locator('#document-list button').filter(has_text='다른 탭의 최신본').first.click()
    expect(content).to_contain_text('다른 탭의 최신본')
    latest = page.request.get(f"{base}/api/sessions/{current}").json()
    assert page.request.put(f"{base}/api/sessions/{current}/draft", data={"markdown":"최종 서버 내용", "base_revision":latest['draft_revision']}).status == 200
    content.click()
    page.keyboard.insert_text("복구 캐시에 보관할 내용")
    expect(page.locator('#draft-conflict')).to_be_visible(timeout=10000)
    page.locator('#reload-draft').click()
    expect(content).to_have_text('최종 서버 내용')
    expect(page.locator('#draft-conflict')).to_be_hidden()
    assert page.evaluate("Object.keys(localStorage).some(k => k.startsWith('div-recovery-') && localStorage[k].includes('복구 캐시에 보관할 내용'))")
    page.screenshot(path="output/postgresql-storage-desktop.png", full_page=True)
    page.set_viewport_size({"width":390,"height":844})
    assert not page.evaluate("document.documentElement.scrollWidth > innerWidth")
    expect(page.locator('#refresh-documents')).to_be_visible()
    expect(page.locator('#new')).to_be_visible()
    page.locator('#refresh-documents').click()
    expect(page.locator('#document-list')).to_contain_text('최종 서버 내용')
    page.screenshot(path="output/postgresql-storage-mobile.png", full_page=True)
    assert not errors, errors
    print("Rich editing, slash commands, tables, checklist, persistence, AI apply/undo/conflict, export, mobile: OK")
    browser.close()
